"""Regenerates service/bawabu_service/popular_npm.py from the npm-high-impact package (MIT).

Run from the repo root:
    uv run python service/scripts/update_popular.py
"""

import io
import json
import re
import tarfile
import urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "bawabu_service" / "popular_npm.py"


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=120) as response:
        return response.read()


def main() -> None:
    meta = json.loads(fetch("https://registry.npmjs.org/npm-high-impact/latest"))
    with tarfile.open(fileobj=io.BytesIO(fetch(meta["dist"]["tarball"]))) as tar:
        source = tar.extractfile("package/lib/top.js").read().decode()
    names = re.findall(r"'([^']+)'", source)
    OUT.write_text(
        f'"""Popular npm package names, most popular first: {len(names)} names from npm-high-impact@{meta["version"]}.\n\n'
        "Source: https://github.com/wooorm/npm-high-impact (MIT). Generated by scripts/update_popular.py; do not edit.\n"
        '"""\n\n'
        f'SOURCE = "npm-high-impact@{meta["version"]}"\n\n'
        'NAMES = """\n' + "\n".join(names) + '\n""".split()\n'
    )
    print(f"wrote {len(names)} names to {OUT}")


if __name__ == "__main__":
    main()
